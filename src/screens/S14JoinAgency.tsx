import React, { useState } from "react";
import { ScreenLayout } from "../components/ScreenLayout";
import { Field } from "../components/Field";
import { Button } from "../components/Button";
import { Logo } from "../components/Logo";
import { Icon } from "../components/Icon";
import { useDemo } from "../context/Demo";

export const S14JoinAgency: React.FC = () => {
  const { go, back, joinAgency, user, signInWithGoogle, staffList } = useDemo();
  const [email, setEmail] = useState("");
  const [tempPassword, setTempPassword] = useState("");
  const [errorMsg, setErrorMsg] = useState<string | null>(null);
  const [joining, setJoining] = useState(false);

  const handleSubmit = async (e: React.FormEvent) => {
    e.preventDefault();
    setErrorMsg(null);
    setJoining(true);
    try {
      const res = await joinAgency(email, tempPassword);
      if (!res.ok) {
        setErrorMsg(
          res.error || "Could not verify staff invitation. Check your code."
        );
      } else {
        go("04");
      }
    } finally {
      setJoining(false);
    }
  };

  return (
    <ScreenLayout
      showBack
      onBack={back}
      title="Join agency"
      hasNav={false}
      contentClassName="overflow-y-auto h-full flex flex-col justify-between pt-2 pb-5"
    >
      <form
        onSubmit={handleSubmit}
        className="flex flex-col justify-between h-full w-full gap-4"
      >
        <div className="flex flex-col gap-4">
          <div className="flex items-center justify-between">
            <Logo size={22} showWordmark={true} />
            <span
              className="px-2.5 py-0.5 rounded-full text-[11px] font-semibold"
              style={{
                backgroundColor: "var(--accent-tint)",
                color: "var(--accent)",
              }}
            >
              Staff Onboarding
            </span>
          </div>

          <div className="flex flex-col gap-1">
            <h1 className="text-[24px] font-extrabold tracking-tight text-[var(--ink)] leading-tight">
              Join your company workspace
            </h1>
            <p className="text-[13px] text-[var(--muted)] leading-relaxed">
              Enter the staff email and temporary password generated by your
              agency owner to link your device to their company database.
            </p>
          </div>

          {!user && (
            <div
              className="p-3.5 rounded-[14px] flex items-center justify-between gap-3"
              style={{ backgroundColor: "var(--surface)", boxShadow: "var(--shadow-subtle)" }}
            >
              <div className="flex flex-col min-w-0">
                <span className="text-[13px] font-bold text-[var(--ink)]">
                  Connect Google first
                </span>
                <span className="text-[11px] text-[var(--muted)]">
                  Required to sync across devices
                </span>
              </div>
              <Button
                type="button"
                variant="soft"
                size="sm"
                onClick={() => signInWithGoogle().catch(() => {})}
              >
                Sign in
              </Button>
            </div>
          )}

          <div className="flex flex-col gap-3">
            <Field
              label="Staff email"
              type="email"
              placeholder="you@company.com"
              value={email}
              className="h-[50px]"
              onChange={(e) => {
                setEmail(e.target.value);
                setErrorMsg(null);
              }}
            />

            <Field
              label="Temporary password / Invite code"
              placeholder="e.g. DOU-7F3K"
              value={tempPassword}
              className="h-[50px]"
              onChange={(e) => {
                setTempPassword(e.target.value.toUpperCase());
                setErrorMsg(null);
              }}
            />
          </div>

          {/* Quick-fill helper if the owner just created a staff invite in this session */}
          {staffList.filter((s) => s.tempPassword).length > 0 && (
            <div
              className="p-3 rounded-[14px] flex flex-col gap-2"
              style={{ backgroundColor: "var(--field)" }}
            >
              <span className="text-[11px] font-semibold text-[var(--muted)] uppercase tracking-wider">
                Active invites created in this agency
              </span>
              <div className="flex flex-col gap-1.5">
                {staffList
                  .filter((s) => s.tempPassword)
                  .map((s) => (
                    <button
                      key={s.id}
                      type="button"
                      onClick={() => {
                        setEmail(s.email);
                        setTempPassword(s.tempPassword || "");
                        setErrorMsg(null);
                      }}
                      className="p-2.5 rounded-[10px] bg-[var(--surface)] flex items-center justify-between text-left cursor-pointer active:scale-[0.99] transition-transform"
                    >
                      <div className="flex flex-col min-w-0">
                        <span className="text-[13px] font-bold text-[var(--ink)] truncate">
                          {s.name} ({s.role})
                        </span>
                        <span className="text-[11px] text-[var(--muted)] truncate">
                          {s.email}
                        </span>
                      </div>
                      <span className="text-[12px] font-mono font-bold text-[var(--accent)] shrink-0 ml-2">
                        {s.tempPassword}
                      </span>
                    </button>
                  ))}
              </div>
            </div>
          )}

          {errorMsg && (
            <div
              className="p-3 rounded-[12px] flex items-center gap-2 text-[13px] font-medium"
              style={{
                backgroundColor: "var(--alert-tint)",
                color: "var(--alert)",
              }}
            >
              <Icon name="close" size={16} color="var(--alert)" />
              <span>{errorMsg}</span>
            </div>
          )}
        </div>

        <div className="pt-3">
          <Button
            type="submit"
            variant="primary"
            className="w-full"
            disabled={joining}
          >
            {joining ? "Verifying..." : "Join agency"}
          </Button>
        </div>
      </form>
    </ScreenLayout>
  );
};
